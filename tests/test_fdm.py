def resolved() -> dict:
    return resolve_presets(process="fdm", machine="bambu-lab-p2s-0.4", material="bambu-pla-basic-p2s",
                           purpose="fdm-general", quality="p2s-0.20-standard", output_format="gcode.3mf")


def vendor_profiles(root: Path) -> Path:
    selection = resolved()
    base = root / "profiles" / "vendor"
    values = {
        "machine": {"nozzle_diameter": ["0.4"], "printable_area": ["0x0", "256x0", "256x256", "0x256"],
                    "printable_height": "256", "machine_start_gcode": "G28\n", "machine_end_gcode": "M104 S0\n"},
        "process": {"inherits": "base-process", "print_extruder_variant": ["Direct Drive Standard", "Direct Drive High Flow"],
                    "inner_wall_speed": ["300", "600"]},
        "filament": {"filament_extruder_variant": ["Direct Drive Standard", "Direct Drive High Flow"],
                     "filament_flow_ratio": ["0.98", "0.98"]},
    }
    for kind, label in (("machine", "machine"), ("process", "quality"), ("filament", "material")):
        directory = base / kind
        directory.mkdir(parents=True)
        name = selection[label]["upstream_profile"]["name"]
        value = {"type": kind, "name": name, "from": "system", **values[kind]}
        if kind != "machine":
            value["compatible_printers"] = [selection["machine"]["upstream_profile"]["name"]]
        (directory / f"{name}.json").write_text(json.dumps(value))
    (base / "process" / "base-process.json").write_text(json.dumps({
        "name": "base-process", "type": "process", "from": "system", "wall_loops": "2", "layer_height": "0.3"}))
    return root / "profiles"


def gcode(motion: str = "G1 X11 Y10 E1\nG1 X11 Y11 E1\n") -> bytes:
    return ("; generated by OrcaSlicer 2.4.2\n; total layer number: 1\n"
            "; model printing time: 1m; total estimated time: 2m\n"
            "G21\nG90\nM83\nG1 X10 Y10 Z0.2\n; CHANGE_LAYER\n; FEATURE: Outer wall\n"
            + motion + "; FEATURE: Custom\nG1 X300 E2\n; filament used [mm] = 5\n").encode()


def sliced_archive(path: Path, profiles: dict, *, code: bytes | None = None, changed: dict | None = None) -> None:
    settings = {}
    for profile in profiles.values():
        settings.update({k: v for k, v in profile.items() if k not in {"type", "name", "from", "compatible_printers"}})
    settings.update(printer_settings_id=profiles["machine"]["name"], filament_settings_id=[profiles["filament"]["name"]])
    settings.update(changed or {})
    code = gcode() if code is None else code
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("Metadata/project_settings.config", json.dumps(settings))
        archive.writestr("Metadata/plate_1.gcode", code)
        archive.writestr("Metadata/plate_1.gcode.md5", hashlib.md5(code).hexdigest())
        archive.writestr("Metadata/slice_info.config", '<config><plate><metadata key="prediction" value="120"/>'
            '<metadata key="weight" value="1"/><metadata key="outside" value="false"/>'
            '<filament id="1"/></plate></config>')


class FDMTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.profile_root = vendor_profiles(self.root)
        self.executable = self.root / "orca-slicer"
        self.executable.write_text("fixture")
        self.config = resolved()

    def profiles(self, config: dict | None = None) -> dict:
        return resolve_fdm_profiles(config or self.config, str(self.executable), self.profile_root)["profiles"]

    def test_inheritance_variant_and_purpose_precedence(self) -> None:
        config = deepcopy(self.config)
        config["purpose"]["supports"]["enabled"] = True
        config["quality"]["settings"]["wall_loops"] = 4
        value = resolve_fdm_profiles(config, str(self.executable), self.profile_root)
        self.assertEqual(value["profiles"]["process"]["wall_loops"], "4")
        self.assertEqual(value["profiles"]["process"]["enable_support"], "1")
        self.assertEqual(value["profiles"]["process"]["inner_wall_speed"], ["300"])
        self.assertEqual(value["profiles"]["filament"]["nozzle_temperature"], ["220"])
        self.assertEqual(value["profiles"]["filament"]["textured_plate_temp_initial_layer"], ["55"])
        self.assertEqual(len(value["sources"]), 4)
        self.assertTrue(all(len(source["sha256"]) == 64 for source in value["sources"]))

    def test_profile_ambiguity_cycle_and_machine_mismatch_block(self) -> None:
        name = self.config["quality"]["upstream_profile"]["name"]
        path = self.profile_root / "vendor/process" / f"{name}.json"
        original = path.read_text()
        value = json.loads(original)
        value["inherits"] = name
        path.write_text(json.dumps(value))
        with self.assertRaisesRegex(ValueError, "cycle"):
            self.profiles()
        path.write_text(original)
        duplicate = self.profile_root / "other/process" / path.name
        duplicate.parent.mkdir(parents=True)
        duplicate.write_text(original)
        with self.assertRaisesRegex(ValueError, "found 2"):
            self.profiles()
        duplicate.unlink()
        machine_path = self.profile_root / "vendor/machine" / f"{self.config['machine']['upstream_profile']['name']}.json"
        value = json.loads(machine_path.read_text())
        value["nozzle_diameter"] = ["0.6"]
        machine_path.write_text(json.dumps(value))
        with self.assertRaisesRegex(ValueError, "nozzle"):
            self.profiles()

    def test_hard_temperature_speed_and_unknown_settings_block(self) -> None:
        with self.assertRaisesRegex(PresetError, "hard limit"):
            resolve_presets(process="fdm", machine="bambu-lab-p2s-0.4", material="bambu-pla-basic-p2s",
                purpose="fdm-general", quality="p2s-0.20-standard", output_format="gcode.3mf",
                overrides={"machine": {"settings": {"max_nozzle_temperature_c": 350}}})
        for key, value, label in (("nozzle_temperature_c", 350, "temperature"), ("flow_ratio", float("nan"), "invalid")):
            config = deepcopy(self.config)
            config["material"]["settings"][key] = value
            with self.assertRaisesRegex(ValueError, label):
                self.profiles(config)
        config = deepcopy(self.config)
        config["quality"]["settings"]["speeds_mm_s"]["travel"] = 700
        with self.assertRaisesRegex(ValueError, "speed limit"):
            self.profiles(config)
        config = deepcopy(self.config)
        config["quality"]["settings"]["unmapped"] = 42
        with self.assertRaisesRegex(ValueError, "unmapped"):
            self.profiles(config)

    def test_saved_settings_and_toolpaths_are_independently_checked(self) -> None:
        profiles = self.profiles()
        path = self.root / "slice.gcode.3mf"
        sliced_archive(path, profiles)
        self.assertEqual(validate_fdm_output(path, resolved=self.config, expected_profiles=profiles)["status"], "passed")
        self.assertEqual(validate_sliced_output(path)["status"], "passed")
        sliced_archive(path, profiles, changed={"nozzle_temperature": ["280"]})
        value = validate_fdm_output(path, resolved=self.config, expected_profiles=profiles)
        self.assertEqual(value["status"], "failed")
        self.assertIn("fdm.saved-setting.nozzle_temperature", [c["id"] for c in value["checks"] if not c["passed"]])
        sliced_archive(path, profiles, code=gcode("G1 X260 E1\n"))
        self.assertEqual(validate_fdm_output(path)["status"], "failed")

    def test_unsliced_3mf_and_multiple_plates_are_rejected(self) -> None:
        path = self.root / "slice.3mf"
        with zipfile.ZipFile(path, "w") as archive:
            archive.writestr("3D/3dmodel.model", "mesh-only")
        self.assertEqual(validate_fdm_output(path)["status"], "failed")
        sliced_archive(path, self.profiles())
        with zipfile.ZipFile(path, "a") as archive:
            archive.writestr("Metadata/plate_2.gcode", gcode())
        self.assertEqual(validate_fdm_output(path)["status"], "failed")

    def test_plain_gcode_expanded_settings_are_checked(self) -> None:
        profiles = self.profiles()
        values = {}
        for profile in profiles.values():
            values.update({k: v for k, v in profile.items() if k not in {"type", "name", "from", "compatible_printers"}})
        values.update(printer_settings_id=profiles["machine"]["name"], filament_settings_id=[profiles["filament"]["name"]])
        comments = ["; CONFIG_BLOCK_START"]
        for key, value in values.items():
            if key in {"machine_start_gcode", "machine_end_gcode"}:
                text = json.dumps(json.dumps(value)[1:-1])[1:-1]
            elif isinstance(value, list):
                separator = "," if key == "printable_area" or key.startswith("machine_max_") else ";"
                text = separator.join(json.dumps(v) if " " in str(v) else str(v) for v in value)
            else:
                text = str(value)
            comments.append(f"; {key} = {text}")
        comments.append("; CONFIG_BLOCK_END")
        path = self.root / "slice.gcode"
        path.write_bytes(("\n".join(comments) + "\n").encode() + gcode())
        self.assertEqual(validate_fdm_output(path, resolved=self.config, expected_profiles=profiles)["status"], "passed")

    def test_relative_absolute_extrusion_and_unsupported_motion(self) -> None:
        relative = _audit_gcode(io.BytesIO(gcode()), [256., 256., 256.])
        absolute_code = gcode("M82\nG92 E0\nG1 X11 E1\nG1 Y11 E2\n")
        absolute = _audit_gcode(io.BytesIO(absolute_code), [256., 256., 256.])
        self.assertEqual(relative["deposited_moves"], absolute["deposited_moves"])
        self.assertEqual(relative["deposited_bounds_mm"], absolute["deposited_bounds_mm"])
        for motion in ("G2 X11 Y11 I1 E1\n", "G02 X11 Y11 I1 E1\n", "G20\nG1 X11 E1\n", "G5 X11 Y11 E1\n"):
            self.assertTrue(_audit_gcode(io.BytesIO(gcode(motion)), [256., 256., 256.])["unsupported_commands"])
        for motion in ("G1 Xnan E1\n", "G1 Xinf E1\n"):
            with self.assertRaisesRegex(ValueError, "nonfinite"):
                _audit_gcode(io.BytesIO(gcode(motion)), [256., 256., 256.])
        travel = _audit_gcode(io.BytesIO(gcode("G17\nG3 Z0.6 I1 J0\nG1 Z0.2\nG1 X11 E1\n")), [256., 256., 256.])
        self.assertEqual(travel["unsupported_commands"], [])
        self.assertEqual(travel["deposited_moves"], 1)

    def test_imported_support_changes_are_not_silently_accepted(self) -> None:
        profiles = self.profiles()
        profiles["process"]["tree_support_branch_distance"] = "3"
        path = self.root / "slice.gcode.3mf"
        sliced_archive(path, profiles, changed={"tree_support_branch_distance": "4"})
        result = validate_fdm_output(path, expected_profiles=profiles,
            native_keys={"process": ["tree_support_branch_distance"]})
        self.assertEqual(result["status"], "failed")
        self.assertIn("fdm.imported-setting.tree_support_branch_distance", [c["id"] for c in result["checks"] if not c["passed"]])

    def test_fdm_orientation_uses_a_flat_bed_face_and_preserves_volume(self) -> None:
        import trimesh
        path = self.root / "box.stl"
        trimesh.creation.box(extents=(10, 20, 30)).export(path)
        result = orient_fdm(path, (256., 256., 256.))
        after = trimesh.load_mesh(path)
        self.assertAlmostEqual(after.extents[2], 10.)
        self.assertAlmostEqual(after.volume, 6000.)
        self.assertEqual(result["selected"]["overhang_area_mm2"], 0)
        self.assertEqual(after.bounds[0].tolist(), [0., 0., 0.])

    def test_multiple_copies_pack_without_factorial_search(self) -> None:
        path = self.root / "cube.stl"
        write_cube(path)
        model = SourceModel(id="cube", source=str(path), sha256=sha256_file(path), quantity=25)
        placements = pack_shelf(root=self.root, models=[model], inspections=[inspect_stl(path)],
                                plate_size_mm=(80., 80., 80.), clearance_mm=2., margin_mm=2.)
        self.assertEqual(len(placements), 25)
        self.assertEqual(len({placement.translate for placement in placements}), 25)
        output = self.root / "plate.stl"
        write_combined_binary_stl(output, placements)
        self.assertEqual(inspect_stl(output).triangle_count, 25 * 12)
        model.quantity = 4097
        with self.assertRaisesRegex(PlatePackingError, "4096"):
            pack_shelf(root=self.root, models=[model], inspections=[inspect_stl(path)],
                       plate_size_mm=(80., 80., 80.), clearance_mm=2., margin_mm=2.)

    def test_fdm_adapter_records_evidence_and_never_disables_backend_checks(self) -> None:
        plate = self.root / "plate.stl"
        write_cube(plate)
        profiles = self.profiles()

        def run(argv, **kwargs):
            if "--help" in argv:
                return BackendResult(argv, 0, "OrcaSlicer-2.4.2:\n", "", {})
            transaction = Path(argv[argv.index("--outputdir") + 1])
            sliced_archive(transaction / "slice.gcode.3mf", profiles)
            (transaction / "result.json").write_text('{"return_code":0}')
            return BackendResult(argv, 0, "", "", {})

        output = self.root / "slice.gcode.3mf"
        with patch("agent_slicer.fdm_adapter.run_backend", side_effect=run):
            result = slice_fdm(plate, output, self.config, executable=str(self.executable),
                               configured_profile_root=self.profile_root, evidence_directory=self.root / "evidence")
        self.assertTrue(output.is_file())
        self.assertEqual(result["status"], "passed")
        self.assertEqual(result["output_sha256"], sha256_file(output))
        self.assertNotIn("--no-check", result["command"])
        self.assertTrue((self.root / "evidence/receipt.json").is_file())

    def test_failed_adapter_preserves_logs_receipt_and_candidate(self) -> None:
        plate = self.root / "plate.stl"
        write_cube(plate)
        profiles = self.profiles()
        def run(argv, **kwargs):
            if "--help" in argv:
                return BackendResult(argv, 0, "OrcaSlicer-2.4.2:\n", "", {})
            sliced_archive(Path(argv[argv.index("--outputdir") + 1]) / "slice.gcode.3mf", profiles, code=gcode("G1 X270 E1\n"))
            return BackendResult(argv, 0, "", "", {})
        output = self.root / "slice.gcode.3mf"
        with patch("agent_slicer.fdm_adapter.run_backend", side_effect=run), self.assertRaisesRegex(RuntimeError, "failed validation"):
            slice_fdm(plate, output, self.config, executable=str(self.executable), configured_profile_root=self.profile_root,
                      evidence_directory=self.root / "evidence")
        self.assertFalse(output.exists())
        receipt = json.loads((self.root / "evidence/receipt.json").read_text())
        self.assertEqual(receipt["status"], "failed")
        self.assertTrue(Path(receipt["rejected_output"]).is_file())

    def test_explicit_backend_is_used_for_planning_and_missing_profiles_block(self) -> None:
        project = init_project(self.root / "project", name="fdm", process="fdm", machine="bambu-lab-p2s-0.4",
            material="bambu-pla-basic-p2s", purpose="fdm-general", quality="p2s-0.20-standard", output_format="gcode.3mf")
        source = self.root / "cube.stl"
        write_cube(source)
        add_models(project, [source])
        _, plan = compile_plan(project, fdm_slicer_path=str(self.executable), fdm_profile_root=self.profile_root)
        self.assertNotIn("fdm.slice", [b.get("capability") for b in plan.blockers])
        self.assertIn("mesh.orient.fdm", plan.required_capabilities)
        self.assertFalse(any(c.startswith("resin.") for c in plan.required_capabilities))
        _, invalid = compile_plan(project, fdm_slicer_path=str(self.executable), fdm_profile_root=self.root / "missing")
        self.assertIn("FDM_PROFILE_INVALID", [b["code"] for b in invalid.blockers])


